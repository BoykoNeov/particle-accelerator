def test_the_two_faces_are_distinguishable_and_do_not_cancel(ref) -> None:
    """An exit-sign slip is self-cancelling in a two-face element; isolate the faces.

    The entrance and the exit are each other's inverse *only* at the same point — so
    ``exit . entry`` is the identity for a zero-length element and is emphatically not
    once a body sits between them. Both statements are asserted, because the first is what
    makes a sign error hide and the second is what exposes it.
    """
    state = STATES[0]
    entry = multipole_fringe_map(state, 1.7, ref, exit_face=False)
    exit_ = multipole_fringe_map(state, 1.7, ref, exit_face=True)
    assert np.abs(entry - exit_).max() > 1e-9

    # back-to-back, with nothing in between: the two faces undo each other
    both = multipole_fringe_map(entry, 1.7, ref, exit_face=True)
    assert np.abs(both - state).max() < 1e-14

    # with a body in between they do not, and that is what tracking gates
    q = Quadrupole(0.6, 1.3, fringe=True)
    assert np.abs(q.track(state, ref) - Quadrupole(0.6, 1.3).track(state, ref)).max() > 1e-9


@pytest.mark.parametrize("state", STATES)
def test_the_gradient_free_face_is_untouched_bit_for_bit(state: np.ndarray, ref) -> None:
    r"""P2 (i)'s and P3 (a)'s face, byte-identical with the two new maps composed in.

    The new maps' ``k1 = 0`` identity is necessary but not sufficient — the *composition*
    could still have shifted, which is what this asserts. ``Dipole(fringe=True)`` on a
    gradient-free bend must still be exactly ``wedge(-e, h) . fringe(h) . wedge(e, 0)``,
    built here by hand rather than read back from the element.
    """
    h, e1, e2 = 0.3 / 1.0, 0.08, 0.05
    bend = Dipole(1.0, 0.3, e1=e1, e2=e2, fringe=True)

    got_entry = bend._face(state, e1, ref, bend.k1, exit_face=False)
    want_entry = wedge_map(
        hard_edge_fringe_map(wedge_map(state, e1, 0.0, ref), h, ref), -e1, h, ref
    )
    assert np.array_equal(got_entry, want_entry)

    got_exit = bend._face(state, e2, ref, bend.k1, exit_face=True)
    want_exit = wedge_map(
        hard_edge_fringe_map(wedge_map(state, -e2, h, ref), -h, ref), e2, 0.0, ref
    )
    assert np.array_equal(got_exit, want_exit)



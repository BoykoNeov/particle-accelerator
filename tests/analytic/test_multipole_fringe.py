# The derivation. Step 2: the Lorentz force turns it into a map.
# ---------------------------------------------------------------------------


#: Two longitudinal ramps on ``[-l, l]``, rising ``0 -> 1``. Both are **C^2** at the
#: joins, and that is a physical requirement, not neatness: the harmonic completion puts a
#: ``g''`` term in the *transverse* field, so a profile whose ``g''`` jumps at the matching
#: plane does not hand back the plain 2D field there and is not comparable with the
#: hard-edge model at all. (A C^1-only ramp was tried and gives a momentum kick of exactly
#: zero — a clean way to lose the whole effect.) Beyond that the shapes are unrelated: the
#: hard-edge answer must not know which one it came from, because only the *moments*
#: ``int g' = 1`` and ``int s g'' = -1`` survive ``l -> 0``. Running the derivation twice
#: is what says so.
def _profile(s: sp.Symbol, half_width: sp.Symbol, index: int) -> sp.Expr:
    u = (s + half_width) / (2 * half_width)
    smoothstep = 10 * u**3 - 15 * u**4 + 6 * u**5
    return [smoothstep, smoothstep + 5 * u**3 * (1 - u) ** 3][index]


def _lorentz_fringe(profile_index: int, *, switching_off: bool) -> dict[str, sp.Expr]:
    r"""The hard-edge fringe of a ``k1`` face, from the field alone.

    Field: ``b = -grad psi`` with ``psi`` the harmonically-completed profile of the first
    test. Motion: ``dpx/ds = y' b_s - b_y`` and ``dpy/ds = b_x - x' b_s`` — exact for a
    straight reference frame, evaluated to **first order in** ``k1`` along the unperturbed
    straight line, which is all the map has (it is exactly linear in ``k1``).

    The fringe map is what is left after the **hard-edge model's own** integral is
    subtracted and the extent ``l -> 0``. Two things survive that limit, and which is
    which is the physics:

    - ``b_s = -g' u`` is ``O(1/l)`` over a range ``O(l)``, so it gives the **momentum**
      kick directly, through ``int g' = 1``;
    - the ``g''`` term of the completed potential is ``O(1/l^2)``, so integrated once it
      makes ``px`` deviate by ``O(1/l)`` *inside* the fringe, and that deviation
      integrated over the extent leaves a finite **position** shift. That is where
      ``x -> x + kappa (x^3 + 3xy^2)/12`` comes from — a map that was a pure momentum
      kick would have missed it, and would not have been symplectic.

    Both position integrals are written with the order of integration swapped,
    ``int ds int_lo^s f dt = int f(t) (hi - t) dt``, which turns a nested sympy
    ``integrate`` into a single one and the runtime from minutes into seconds.
    """
    x0, y0, xp, yp, delta, k1 = sp.symbols("x0 y0 xp yp delta k1", real=True)
    s = sp.Symbol("s", real=True)
    half = sp.Symbol("half", positive=True)
    xx, yy = sp.symbols("xx yy", real=True)

    g = _profile(s, half, profile_index)
    if switching_off:
        g = g.subs(s, -s)  # the same ramp reversed: the field is on *before* this face

    u2d = -k1 * xx * yy  # b = -grad psi  ->  (b_x, b_y) = (k1 y, k1 x)
    psi = g * u2d - sp.diff(g, s, 2) * (xx**2 + yy**2) * u2d / 12
    b = (-sp.diff(psi, xx), -sp.diff(psi, yy), -sp.diff(psi, s))
    b_hard = (k1 * yy, k1 * xx, sp.Integer(0))  # the plain 2D field, body side only

    lo_h = -half if switching_off else sp.Integer(0)
    hi_h = sp.Integer(0) if switching_off else half
    traj = {xx: x0 + xp * s, yy: y0 + yp * s}
    force = [sp.expand((yp * b[2] - b[1]).subs(traj)), sp.expand((b[0] - xp * b[2]).subs(traj))]
    force_h = [
        sp.expand((yp * b_hard[2] - b_hard[1]).subs(traj)),
        sp.expand((b_hard[0] - xp * b_hard[2]).subs(traj)),
    ]

    def _integrate(f: sp.Expr, lo: sp.Expr, hi: sp.Expr, weight: sp.Expr | None = None) -> sp.Expr:
        return sp.integrate(f if weight is None else sp.expand(f * weight), (s, lo, hi))

    kick = [_integrate(force[i], -half, half) - _integrate(force_h[i], lo_h, hi_h) for i in (0, 1)]
    shift = [
        (_integrate(force[i], -half, half, half - s) - _integrate(force_h[i], lo_h, hi_h, hi_h - s))
        / (1 + delta)
        for i in (0, 1)
    ]

    eps = sp.Symbol("eps", positive=True)
    scale = {x0: eps * x0, y0: eps * y0, xp: eps * xp, yp: eps * yp}

    def _cubic(expr: sp.Expr) -> sp.Expr:
        limited = sp.limit(sp.cancel(sp.expand(expr)), half, 0)
        return sp.expand(sp.expand(limited).subs(scale)).coeff(eps, 3)

    return {
        "px": _cubic(kick[0]),
        "py": _cubic(kick[1]),
        "x": _cubic(shift[0]),
        "y": _cubic(shift[1]),
    }


def _shipped_first_order(switching_off: bool) -> dict[str, sp.Expr]:
    """The shipped map's own displacements, expanded to first order in ``k1``.

    Symbols, not floats — so the comparison against the derivation is an identity in
    ``(x, y, x', y', delta)``, not an agreement at a handful of sampled amplitudes.
    """
    x0, y0, xp, yp, delta, k1 = sp.symbols("x0 y0 xp yp delta k1", real=True)
    kappa = -k1 if switching_off else k1
    rpp = 1 / (1 + delta)
    fx = -kappa * (x0**3 + 3 * x0 * y0**2) / 12
    fy = kappa * (3 * x0**2 * y0 + y0**3) / 12
    # px = (1 + delta) x' is the paraxial identification the derivation's x' makes.
    px, py = xp * (1 + delta), yp * (1 + delta)
    fxx, fxy = sp.diff(fx, x0), sp.diff(fx, y0)
    fyx, fyy = sp.diff(fy, x0), sp.diff(fy, y0)
    return {
        "x": -fx * rpp,
        "y": -fy * rpp,
        "px": fxx * rpp * px + fyx * rpp * py,
        "py": fxy * rpp * px + fyy * rpp * py,
    }


def _identical(a: sp.Expr, b: sp.Expr) -> bool:
    """``a == b`` as rational functions — cleared of the common ``1/(1+delta)`` first."""
    delta = sp.Symbol("delta", real=True)
    return sp.expand(sp.cancel((a - b) * (1 + delta))) == 0


@pytest.mark.parametrize("profile_index", [0, 1])
def test_the_lorentz_integral_through_a_vanishing_fringe_is_the_shipped_map(
    profile_index: int,
) -> None:
    r"""The whole map, derived from the field — coefficient, structure and **sign**.

    This is the gate the milestone actually rests on. Everything else in the file passes
    for a map whose ``1/12`` is any other number; this one does not, and it reaches the
    answer through Maxwell and the Lorentz force without consulting xtrack, MAD-NG or the
    shipped code.

    Run for **two different ramps**, which is the statement that the hard-edge limit is
    profile-independent — the physical content of calling it a *hard-edge* fringe.
    """
    derived = _lorentz_fringe(profile_index, switching_off=False)
    shipped = _shipped_first_order(switching_off=False)
    for key in ("x", "y", "px", "py"):
        assert _identical(derived[key], shipped[key]), key


def test_the_exit_face_is_the_same_derivation_with_the_field_switching_off() -> None:
    r"""``kappa`` flips sign at the exit, and the derivation says so rather than the code.

    An exit-face sign error is **partially self-cancelling** — with both faces on, the
    wrong sign changes the magnitude but leaves the structure intact — so it is the error
    least likely to be caught by a whole-element comparison. Here the field ramps *down*
    across the face instead of up, ``int g'`` becomes ``-1``, and every displacement
    reverses. Nothing else about the derivation changes.
    """
    derived = _lorentz_fringe(0, switching_off=True)
    shipped = _shipped_first_order(switching_off=True)
    for key in ("x", "y", "px", "py"):
        assert _identical(derived[key], shipped[key]), key

    entry = _shipped_first_order(False)
    assert all(_identical(shipped[k], -entry[k]) for k in ("x", "y", "px", "py"))



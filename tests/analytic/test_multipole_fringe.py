@pytest.mark.parametrize("state", STATES)
def test_zero_gradient_is_the_identity_bit_for_bit(state: np.ndarray, ref) -> None:
    """``k1 = 0`` returns the input unchanged — no rounding, no branchless arithmetic."""
    for exit_face in (False, True):
        assert np.array_equal(multipole_fringe_map(state, 0.0, ref, exit_face=exit_face), state)
    assert np.array_equal(
        Quadrupole(0.6, 0.0, fringe=True).track(state, ref),
        Quadrupole(0.6, 0.0).track(state, ref),
    )


def test_the_approach_to_the_identity_is_linear_in_k1(ref) -> None:
    """Slope **exactly one**, which is also why this gate cannot see the ``1/12``.

    P2 (ii)'s short-circuit and P2 (iv)'s ``k1 -> 0`` limit both turned on gating the
    *approach* rather than only the endpoint, so it is asserted here too. What it buys is
    the absence of a discontinuity at zero; what it explicitly does **not** buy is the
    coefficient, since a map scaled by any constant has the same unit slope.
    """
    state = STATES[0]
    base = np.abs(multipole_fringe_map(state, 1.0, ref) - state).max()
    for k1 in (1e-2, 1e-3, 1e-4):
        got = np.abs(multipole_fringe_map(state, k1, ref) - state).max()
        assert got == pytest.approx(k1 * base, rel=1e-12)


def test_the_effect_is_cubic_in_the_amplitude(ref) -> None:
    """Order **three**, measured as an order and not as a tolerance — J2/J3's rule.

    A cubic map mis-scaled by a constant is invisible to this too; what it catches is a
    map that picked up a linear or quadratic term, which is the failure that would move
    ``matrix`` or the second-order map underneath the next test.
    """
    state = STATES[0].copy()
    ratios = []
    prev = None
    for scale in (1.0, 0.5, 0.25, 0.125):
        st = state * scale
        st[DELTA] = state[DELTA]  # delta is not an amplitude here
        size = np.abs(multipole_fringe_map(st, 1.7, ref)[[X, PX, Y, PY]] - st[[X, PX, Y, PY]]).max()
        if prev is not None:
            ratios.append(prev / size)
        prev = size
    assert all(r == pytest.approx(8.0, rel=1e-6) for r in ratios), ratios


def test_no_first_or_second_order_quantity_moves(ref) -> None:
    r"""The pre-committed gate: a cubic map must not reach ``matrix``, the tunes or ``T``.

    Asserted, not hoped. ``matrix`` and the Twiss are compared **bit for bit**; the
    second-order map to ``1e-15``, which is a finite-difference floor and not a tolerance
    on physics — ``taylor_expand`` differences the tracked map numerically.

    This is also the statement that MAD-X's ``sectormap`` and PTC at ``no = 2`` cannot
    arbitrate this milestone: they would see exactly the zero on the right-hand side.
    """
    plain = [Drift(0.4), Quadrupole(0.6, 1.3), Drift(0.4), Quadrupole(0.6, -1.3)]
    fringed = [
        Drift(0.4),
        Quadrupole(0.6, 1.3, fringe=True),
        Drift(0.4),
        Quadrupole(0.6, -1.3, fringe=True),
    ]
    lat_a, lat_b = Lattice(plain, ref), Lattice(fringed, ref)

    assert np.array_equal(lat_a.one_turn_matrix(), lat_b.one_turn_matrix())
    assert tunes(lat_a) == tunes(lat_b)
    tw_a, tw_b = closed_twiss(lat_a), closed_twiss(lat_b)
    assert tw_a.beta_x == tw_b.beta_x
    assert tw_a.beta_y == tw_b.beta_y

    # The exact statement is on the analytic matrices, and it is bit for bit.
    assert np.array_equal(
        Quadrupole(0.6, 1.3, fringe=True).matrix(ref), Quadrupole(0.6, 1.3).matrix(ref)
    )
    # The *tracked* map says the same thing to a finite-difference floor: a central
    # difference does not cancel a cubic term, it leaves O(step^2) of it in R and O(step)
    # in T, so these are the differencing scheme's residues, not the fringe's.
    q_a = taylor_expand(lambda s: Quadrupole(0.6, 1.3).track(s, ref), np.zeros(DIM))
    q_b = taylor_expand(lambda s: Quadrupole(0.6, 1.3, fringe=True).track(s, ref), np.zeros(DIM))
    np.testing.assert_allclose(q_b.R, q_a.R, rtol=0.0, atol=1e-12)
    np.testing.assert_allclose(q_b.T, q_a.T, rtol=0.0, atol=1e-8)
    # ...and there really is something for the *tracked* map to differ by.
    moved = Quadrupole(0.6, 1.3, fringe=True).track(STATES[0], ref) - Quadrupole(0.6, 1.3).track(
        STATES[0], ref
    )
    assert np.abs(moved).max() > 1e-9


def test_nothing_first_order_moves_on_a_gradient_bend_either(ref) -> None:
    r"""The same gate on the element the refusal was actually on — and it is not the same test.

    ``Quadrupole``'s version above is the easy half: the only new map there is *cubic*, and
    a cubic map cannot reach a linear quantity. A **rotated gradient** bend inserts a
    *quadratic* map into P3 (a)'s composition, and P3 (a)'s headline was precisely that the
    composed face's origin Jacobian **is** :func:`~accsim.elements.dipole._edge_matrix`. So
    the claim being re-made here is that a centred quadratic kick has a zero Jacobian at the
    origin and leaves that identity standing —
    :func:`~accsim.elements.dipole.curvature_sextupole_kick`'s docstring argues exactly
    that, which is the kind of "should" this project measures rather than believes.

    Nothing before P3 (b) could have covered this: the constructor *raised*.
    """
    L, angle, k1, e1, e2 = 1.0, 0.3, 0.4, 0.08, 0.05

    def bend(fringe: bool, sign: float = 1.0) -> Dipole:
        return Dipole(L, angle, k1=sign * k1, e1=e1, e2=e2, fringe=fringe)

    # 1. the element's own linear map, bit for bit
    assert np.array_equal(bend(True).matrix(ref), bend(False).matrix(ref))

    # 2. and every optics quantity a ring of them reports. The gradient has to alternate
    #    -- a ring of like-signed combined bends is vertically unstable, and an
    #    UnstableLatticeError would have made this gate pass by never running.
    def ring(fringe: bool) -> Lattice:
        return Lattice([bend(fringe, +1.0), Drift(0.5), bend(fringe, -1.0), Drift(0.5)] * 2, ref)

    off, on = ring(False), ring(True)
    assert np.array_equal(off.one_turn_matrix(), on.one_turn_matrix())
    assert tunes(off) == tunes(on)
    tw_off, tw_on = closed_twiss(off), closed_twiss(on)
    assert tw_off.beta_x == tw_on.beta_x
    assert tw_off.beta_y == tw_on.beta_y
    assert natural_chromaticity(off) == natural_chromaticity(on)

    # 3. matrix() is still the origin Jacobian of track(), and the residual is the
    #    finite-difference floor rather than a physical gap: it falls with the step.
    fringed = bend(True)
    residuals = [
        float(
            np.abs(
                jacobian(lambda s: fringed.track(s, ref), np.zeros(DIM), h) - fringed.matrix(ref)
            ).max()
        )
        for h in (1e-4, 1e-5)
    ]
    assert residuals[1] < residuals[0]
    assert residuals[1] < 1e-9

    # 4. ...and the face is emphatically doing something to the *tracked* state.
    assert np.abs(fringed.track(STATES[0], ref) - bend(False).track(STATES[0], ref)).max() > 1e-6



def test_maxwell_fixes_the_twelve() -> None:
    r"""A quadrupole with a longitudinal profile is **not** ``g(s)`` times the 2D field.

    ``grad^2 psi = 0`` will not allow it: the ``g''`` the profile introduces has to be
    absorbed by a transverse term one order higher in the radius. For a 2D harmonic ``u``
    of degree ``N``,

        grad_perp^2 (r^2 u) = 4 (N + 1) u      [Euler: x d_x + y d_y = N on u]

    so ``psi = g u - g'' r^2 u / (4(N+1)) + O(g'''')`` is the unique continuation whose
    on-axis expansion coefficients are the derivatives of ``g`` — the generalised-gradient
    form MAD-NG and PTC both assume, and the one a real magnet with distant sources has.

    A quadrupole is ``N = 2``, giving ``-1/12``. **That is the 12 in the shipped map**,
    and nothing in the code below is consulted to get it. The dipole's ``N = 1`` and the
    sextupole's ``N = 3`` are checked alongside, because a coefficient that came out right
    for one degree by accident would not stay right across three.
    """
    x, y, s, c1 = sp.symbols("x y s c1", real=True)
    g = sp.Function("g")(s)

    for degree, u in ((1, y), (2, x * y), (3, 3 * x**2 * y - y**3)):
        assert sp.simplify(sp.diff(u, x, 2) + sp.diff(u, y, 2)) == 0, "u must be harmonic"
        psi = g * u + c1 * sp.diff(g, s, 2) * (x**2 + y**2) * u
        lap = sp.expand(sp.diff(psi, x, 2) + sp.diff(psi, y, 2) + sp.diff(psi, s, 2))
        solved = sp.solve(sp.Eq(lap.coeff(sp.diff(g, s, 2)), 0), c1)
        assert solved == [sp.Rational(-1, 4 * (degree + 1))], degree

    quad_c1 = sp.Rational(-1, 4 * (2 + 1))
    assert quad_c1 == sp.Rational(-1, 12)



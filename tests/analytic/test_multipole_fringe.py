@pytest.mark.parametrize("state", STATES)
def test_the_quad_wedge_is_the_curvature_sextupole_kick(state: np.ndarray) -> None:
    r"""The same expression, and the reason is physical, not numerological.

    Both are the quadrupole potential integrated over a path length that varies linearly
    in ``x``: the body's ``(1 + h x)`` metric factor over ``L`` gives ``h k1 L``, the
    wedge's geometric sliver ``x tan(e)`` gives ``k1 theta``. A bend's ``theta = h L``, so
    the two integrated strengths are one expression. Asserted rather than assumed — the
    advisorial worry is exactly that two maps of the same *shape* get merged when their
    strengths happen to coincide in one element and not in another.
    """
    for theta, k1 in ((0.08, 1.3), (-0.05, 0.4), (0.2, -2.0)):
        assert np.array_equal(
            quad_wedge_map(state, theta, k1), curvature_sextupole_kick(state, k1 * theta)
        )
    assert np.array_equal(quad_wedge_map(state, 0.0, 1.3), state)
    assert np.array_equal(quad_wedge_map(state, 0.08, 0.0), state)


def test_the_quad_wedge_is_the_one_piece_that_moves_the_second_order_map(ref) -> None:
    r"""Quadratic, not cubic — so ``T`` *does* move, and only on a **rotated** face.

    The comparison has to be **face against face**, not bend against bend: P2 (i)'s dipole
    fringe already moves ``T`` by ``0.19`` on this magnet, so ``fringe=True`` versus
    ``fringe=False`` would drown the gradient's share entirely. Against the same face with
    the two gradient maps left out:

    - at ``e = 0`` the gap is the finite-difference floor — the multipole fringe is cubic
      and reaches ``T`` not at all, which is the pre-committed gate and the reason
      ``sectormap`` and PTC at ``no = 2`` are vacuous here;
    - at ``e != 0`` it is the wedge's own entries, ``k1 theta`` split ``2:-1`` by Maxwell.
    """
    L, angle, k1 = 1.0, 0.3, 0.4
    h = angle / L

    def _face_T(e: float, *, gradient: bool) -> np.ndarray:
        def face(st: np.ndarray) -> np.ndarray:
            out = wedge_map(st, e, 0.0, ref)
            out = hard_edge_fringe_map(out, h, ref)
            if gradient:
                out = multipole_fringe_map(out, k1, ref, exit_face=False)
                out = quad_wedge_map(out, -e, k1)
            return wedge_map(out, -e, h, ref)

        return taylor_expand(face, np.zeros(DIM)).T

    sector_gap = _face_T(0.0, gradient=True) - _face_T(0.0, gradient=False)
    assert np.abs(sector_gap).max() < 1e-9, "a cubic face must not reach T"

    rotated_gap = _face_T(0.08, gradient=True) - _face_T(0.08, gradient=False)
    assert np.abs(rotated_gap).max() > 1e-3, "the quad wedge must reach T"

    # ...and the entries it lands on are the wedge's own, entry for entry.
    theta = -0.08
    wedge_only = taylor_expand(lambda s: quad_wedge_map(s, theta, k1), np.zeros(DIM))
    assert wedge_only.T[PX, X, X] == pytest.approx(-k1 * theta, rel=1e-6)
    assert wedge_only.T[PX, Y, Y] == pytest.approx(k1 * theta / 2.0, rel=1e-6)
    assert wedge_only.T[PY, X, Y] == pytest.approx(k1 * theta / 2.0, rel=1e-6)



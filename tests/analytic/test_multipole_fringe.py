def test_the_time_term_is_the_generating_functions_own() -> None:
    r"""``zeta``'s share, derived from the F2 rather than compared against a reference.

    It is the half of the map **no** reference leg in this milestone can see. The xtrack
    comparison runs at ``gamma0 = 20``, where ``E/E0`` and ``1`` differ by less than every
    tolerance in the file; ``sectormap`` and PTC at ``no = 2`` cannot see a cubic term at
    all. P2 (i) hit exactly this and reached for symplecticity — which works there because
    the dipole fringe's ``zeta`` term is comparable in size to its transverse ones. Here it
    is not: the whole map is cubic, so a 0.1% error in ``zeta`` is a ``5e-14`` perturbation
    of a Poisson bracket, and a finite-difference symplecticity check does **not** resolve
    it. (Measured — the variant with the factor dropped passes
    :func:`~accsim.is_symplectic_map_canonical` at ``gamma0 = 1.5``.)

    So it is derived instead, and exactly. With ``tau = zeta/beta0`` conjugate to
    ``p_tau``, the map is generated by ``F2 = P . g(q, p_tau) + tau p_tau'`` with
    ``g = q - f(q)/(1 + delta)``; reading ``T = dF2/dp_tau`` and using
    ``ddelta/dp_tau = (1/beta0 + p_tau)/(1 + delta)`` gives

        zeta -> zeta + (1 + beta0 p_tau) (P . f)/(1 + delta)^3,

    and ``1 + beta0 p_tau`` **is** ``E/E0``. That is the shipped line, factor for factor.
    """
    x, y, px, py, ptau, k1, beta0 = sp.symbols("x y px py ptau k1 beta0", real=True)
    delta = sp.sqrt(1 + 2 * ptau / beta0 + ptau**2) - 1
    rpp = 1 / (1 + delta)

    fx = -k1 * (x**3 + 3 * x * y**2) / 12
    fy = k1 * (3 * x**2 * y + y**3) / 12
    gx, gy = x - fx * rpp, y - fy * rpp

    jac = sp.Matrix([[sp.diff(gx, x), sp.diff(gx, y)], [sp.diff(gy, x), sp.diff(gy, y)]])
    big_p = jac.T.inv() * sp.Matrix([px, py])  # p = J^T P  ->  P = J^-T p

    # zeta = beta0 tau, so the zeta increment is beta0 (P . dg/dp_tau).
    derived = beta0 * (big_p[0] * sp.diff(gx, ptau) + big_p[1] * sp.diff(gy, ptau))
    shipped = (1 + beta0 * ptau) * rpp**3 * (big_p[0] * fx + big_p[1] * fy)
    assert sp.simplify(derived - shipped) == 0

    # and the code's hypot form of E/E0 is that same 1 + beta0 p_tau, numerically
    for gamma0 in (1.5, 20.0):
        r = ReferenceParticle.from_gamma(MASS0, gamma0)
        for d in (-0.02, 0.0, 0.03):
            e_over_e0 = np.hypot(r.momentum_eV * (1 + d), r.mass_eV) / r.total_energy_eV
            ptau_num = (e_over_e0 - 1.0) / r.beta0
            assert e_over_e0 == pytest.approx(1 + r.beta0 * ptau_num, rel=1e-15)



r"""P2 (i) — the hard-edge dipole fringe, the second-order map of a field that stops.

A sector bend's body field does not depend on ``y``, so nothing in the linear matrix and
nothing in the exact circle of L3 couples the planes. That is a statement about the
*inside* of the magnet. At the face the field stops, and ``curl B = 0`` will not let it
stop only in ``B_y``: a longitudinal component ``B_s = y dB_y/ds`` appears — a delta
function at a hard edge — whose impulse is a **vertical** kick proportional to the
*horizontal* angle. Every entry the fringe adds to the second-order map therefore
carries a ``y``, in a magnet that bends horizontally, which is exactly the signature P1
measured against MAD-X before any of this was written.

**What is derived here and what is imported.** The map is generated by

    Phi(px, py, delta) = h px pz / ((1 + delta)^2 - px^2),
    W = -Phi(p) ybar^2 / 2,

so the three gradients of ``Phi`` *are* the map, and they are re-derived here with sympy
from ``Phi`` alone and compared against the closed forms
:func:`~accsim.elements.dipole.hard_edge_fringe_map` evaluates — the project's rule that
a coefficient is derived, not recalled. The five entries MAD-X's ``sectormap`` pins are
then re-derived a second way, by composing the fringe's own ``T`` with the body's ``R``
under P1's rule, and the *whole* ``6x6x6`` gap is checked that way, not only the five:
the probe that opened this milestone found **twelve** distinct nonzero entries, of which
P1 had named five.

**The gate the reference legs cannot supply.** ``zeta``'s share of the fringe is
``Phi_delta ybar^2``, which is *cubic*, so it is absent from ``T`` — MAD-X's
``sectormap``, PTC's ``maptable`` and the five pinned entries are all blind to it. What
is not blind to it is **symplecticity**: ``x``'s dependence on ``delta`` and ``zeta``'s
on ``px`` are conjugate halves of the same generating function, so the ``beta0/beta``
conversion between ``tau`` and ``zeta`` is gated exactly once, by
:func:`~accsim.symplectic.is_symplectic_map_canonical`. That is asserted here both ways:
the map passes, and a variant with the conversion dropped fails.
"""


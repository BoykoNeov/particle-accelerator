def _ring(ref: ReferenceParticle, *, fringe: bool) -> Lattice:
    cell = [
        Quadrupole(0.3, 1.2),
        Drift(0.5),
        Dipole(L_B, ANGLE, fringe=fringe),
        Quadrupole(0.3, -1.2),
        Drift(0.5),
    ]
    return Lattice(cell * 8, ref)


def test_the_origin_jacobian_is_the_identity_so_no_optics_moves(ref: ReferenceParticle) -> None:
    r"""Every first-order quantity in the package is **bit-identical** with the fringe on.

    The fringe's terms are all quadratic (``ybar^2``, and ``Phi ybar`` with ``Phi(0) =
    0``), so its Jacobian at the origin is the identity — not merely close to it. That
    makes the claim exact rather than tolerated: ``matrix``, the tunes, ``beta``, the
    dispersion and the natural chromaticity of a ring are the *same floats*. It is also
    why P1 was needed to find the gap at all: no first-order cross-check could.
    """
    J = jacobian(lambda s: hard_edge_fringe_map(s, H, ref), np.zeros(DIM), 1e-6)
    np.testing.assert_allclose(J, np.eye(DIM), atol=1e-12)

    plain, fringed = Dipole(L_B, ANGLE), Dipole(L_B, ANGLE, fringe=True)
    assert np.array_equal(plain.matrix(ref), fringed.matrix(ref))

    off, on = _ring(ref, fringe=False), _ring(ref, fringe=True)
    t_off, t_on = closed_twiss(off), closed_twiss(on)
    assert np.array_equal(t_off.beta_x, t_on.beta_x)
    assert np.array_equal(t_off.beta_y, t_on.beta_y)
    assert np.array_equal(t_off.disp_x, t_on.disp_x)
    assert tunes(off) == tunes(on)
    assert natural_chromaticity(off) == natural_chromaticity(on)


def test_fringe_off_is_the_shipped_bend_bit_for_bit(ref: ReferenceParticle) -> None:
    """The default is unchanged — a whole bunch through both maps, ``array_equal``."""
